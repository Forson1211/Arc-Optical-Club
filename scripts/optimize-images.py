"""Generate responsive WebP assets; keep the source photos untouched."""
from pathlib import Path
from io import BytesIO
import hashlib
import json
import re
from PIL import Image, ImageOps

ROOT = Path(__file__).resolve().parents[1]
PUBLIC = ROOT / 'frontend' / 'public'
manifest = {}
source_bytes = output_bytes = 0

for folder in ('images', 'scrolling'):
    for source in sorted((PUBLIC / folder).iterdir()):
        if source.suffix.lower() not in ('.jpg', '.jpeg', '.png', '.webp'):
            continue
        with Image.open(source) as original:
            image = ImageOps.exif_transpose(original)
            image = image.convert('RGBA' if 'A' in image.getbands() else 'RGB')
            width, height = image.size
            logo = 'logo' in source.stem.lower()
            sizes = sorted(set(min(width, size) for size in ([256, 512] if logo else [480, 960, 1440])))
            variants = []
            stem = re.sub(r'[^a-z0-9]+', '-', source.stem.lower()).strip('-')
            for size in sizes:
                resized = image.resize((size, max(1, round(height * size / width))), Image.Resampling.LANCZOS)
                buffer = BytesIO()
                if logo:
                    resized.save(buffer, 'WEBP', lossless=True, method=6)
                else:
                    resized.save(buffer, 'WEBP', quality=80, method=6)
                encoded = buffer.getvalue()
                digest = hashlib.sha256(encoded).hexdigest()[:12]
                destination = PUBLIC / 'optimized' / folder / f'{stem}-{size}-{digest}.webp'
                destination.parent.mkdir(parents=True, exist_ok=True)
                destination.write_bytes(encoded)
                variants.append({'src': '/' + destination.relative_to(PUBLIC).as_posix(), 'width': size})
                output_bytes += destination.stat().st_size
            source_bytes += source.stat().st_size
            manifest['/' + source.relative_to(PUBLIC).as_posix()] = {
                'src': variants[-1]['src'],
                'srcSet': ', '.join(f"{variant['src']} {variant['width']}w" for variant in variants),
                'width': width,
                'height': height,
            }

target = ROOT / 'frontend' / 'src' / 'data' / 'image-manifest.ts'
target.write_text('// Generated by scripts/optimize-images.py. Keep source photos in public/.\n'
                  'export const imageManifest: Record<string, { src: string; srcSet: string; width: number; height: number }> = '
                  + json.dumps(manifest, indent=2) + '\n', encoding='utf-8')
print(f'{len(manifest)} images: sources {source_bytes / 1048576:.2f} MB; all responsive variants {output_bytes / 1048576:.2f} MB')
